def text_to_sql_endpoint(prompt: str):
    prompt_lower = prompt.lower().strip()

    if any(w in prompt_lower for w in ["chào", "hi", "hello", "bạn là ai"]):
        return {"status": "success", "reply": "👋 Chào bạn, tôi là trợ lý AI quản lý kho VLXD."}

