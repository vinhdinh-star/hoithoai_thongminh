def clean_and_execute_sql(question_text):
    prompt = f"""<|im_start|>system
Bạn là chuyên gia SQLite SQL hàng đầu. Hãy viết một truy vấn SQLite hợp lệ để trả lời câu hỏi dựa trên schema sau. Lưu ý sử dụng bảng nhan_vien (manv, hoten, chucvu) thay thế cho NhanVien:
{database_schema}
Chỉ xuất ra câu lệnh SQL hoàn chỉnh bắt đầu bằng SELECT và kết thúc bằng dấu chấm phẩy.
<|im_end|>
<|im_start|>user
{question_text}<|im_end|>
<|im_start|>assistant
SELECT """

    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    with torch.no_grad():
        outputs = model.generate(**inputs, max_new_tokens=150, temperature=0.01, do_sample=False)

    raw_output = tokenizer.decode(outputs[0], skip_special_tokens=True)
    sql_query = "SELECT " + raw_output.split("SELECT")[-1] if "SELECT" in raw_output else raw_output

    # Trích xuất chuẩn xác lệnh SQL duy nhất
    match = re.search(r"(SELECT\s+.*?;)", sql_query, re.IGNORECASE | re.DOTALL)
    clean_sql = match.group(1).strip() if match else sql_query.strip().split("\n")[0]

    # Chuẩn hóa nhanh câu lệnh SQL tự động sửa lỗi ánh xạ bảng NhanVien lỗi sang nhan_vien
    clean_sql = re.sub(r'\bNhanVien\b', 'nhan_vien', clean_sql, flags=re.IGNORECASE)
    clean_sql = re.sub(r'\bMaNV\b', 'manv', clean_sql, flags=re.IGNORECASE)
    clean_sql = re.sub(r'\bHoTen\b', 'hoten', clean_sql, flags=re.IGNORECASE)
    clean_sql = re.sub(r'\bChucVu\b', 'chucvu', clean_sql, flags=re.IGNORECASE)

    # Thực thi và lấy kết quả dạng bảng
    try:
        conn = sqlite3.connect(DB_PATH)
        df_res = pd.read_sql_query(clean_sql, conn)
        conn.close()
        if df_res.empty:
            data_out = "Không có dữ liệu thỏa mãn"
        else:
            # Giới hạn hiển thị tối đa 3 dòng kết quả cho gọn báo cáo
            data_out = df_res.head(3).to_dict(orient='records')
    except Exception as e:
        data_out = f"Lỗi truy vấn: {str(e)}"

    return clean_sql, data_out

