    result = generate_and_execute_sql(prompt)

    if result["status"] == "error":
        return {
            "status": "error",
            "reply": f"⚠️ Lỗi thực thi SQL: {result['message']} \n- Câu lệnh gây lỗi: `{result['sql_query']}`"
        }

