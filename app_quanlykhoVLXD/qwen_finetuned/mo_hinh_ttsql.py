def generate_and_execute_sql(user_query: str):
    # 1. Xây dựng prompt chuẩn ChatML của Qwen
    prompt = f"""<|im_start|>system
Bạn là một công cụ dịch Text-to-SQL cho SQLite chuyên nghiệp. Chỉ xuất ra câu lệnh SQL hợp lệ dựa vào schema sau:
{database_schema}
<|im_end|>
<|im_start|>user
{user_query}<|im_end|>
<|im_start|>assistant
SELECT """

    # 2. Tokenize và sinh câu lệnh từ model
    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    outputs = model.generate(
        **inputs,
        max_new_tokens=150,
        temperature=0.01,
        do_sample=False
    )

    raw_output = tokenizer.decode(outputs[0], skip_special_tokens=True)

    # 3. Ghép lại chữ SELECT và dùng Regex lấy trọn vẹn câu lệnh SQL
    full_text = "SELECT " + raw_output.split("SELECT")[-1] if "SELECT" in raw_output else raw_output

    match = re.search(r"(SELECT\s+.*?;)", full_text, re.IGNORECASE | re.DOTALL)
    if match:
        sql_query = match.group(1)
    else:
        sql_query = full_text.split("\n")[0].strip()

    # 4. Thực thi câu lệnh SQL vào SQLite
    try:
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        cursor.execute(sql_query)
        rows = cursor.fetchall()
        conn.close()

        return {
            "status": "success",
            "sql_query": sql_query,
            "data": rows
        }
    except Exception as e:
        return {
            "status": "error",
            "sql_query": sql_query,
            "message": str(e)
        }

