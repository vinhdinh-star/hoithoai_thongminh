import sqlite3

def evaluate_sql_execution(db_path, pred_sql, true_sql):
    """
    So sánh kết quả thực thi của SQL dự đoán và SQL chuẩn trên database SQLite.
    Trả về True nếu kết quả giống nhau, False nếu khác hoặc lỗi.
    """
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    try:
        # Thực thi SQL chuẩn (Ground-truth)
        cursor.execute(true_sql)
        true_result = cursor.fetchall()
    except Exception as e:
        conn.close()
        return {"match": False, "error": f"Lỗi SQL chuẩn: {str(e)}"}

    try:
        # Thực thi SQL do mô hình sinh ra
        cursor.execute(pred_sql)
        pred_result = cursor.fetchall()
    except Exception as e:
        conn.close()
        return {"match": False, "error": f"Lỗi SQL mô hình: {str(e)}"}

    conn.close()

    # So sánh tập kết quả (có thể sắp xếp lại hoặc so sánh trực tiếp tùy bài toán)
    is_match = (set(true_result) == set(pred_result))
    return {"match": is_match, "true_result": true_result, "pred_result": pred_result}

